// 변수 이름: 긴 것부터 바꿔야 '스프레이 1 시간'이 '스프레이 시간'보다 먼저 맞는다
const LABELS = Object.values(VARIABLES)
  .map((v) => [v.ko, v.en])
  .sort((a, b) => b[0].length - a[0].length);

const fill = (template, params = {}) => String(template).replace(/\{(\w+)\}/g, (_, k) => (k in params ? params[k] : `{${k}}`));

export class Localizer {
  constructor(lang = "ko") {
    this.lang = LANGS.includes(lang) ? lang : "ko";
    this.dict = UI[this.lang];
  }

  /** UI 문구. 영어 사전에 없으면 한국어 문구를 쓴다. */
  t(key, params) {
    return fill(this.dict[key] ?? UI.ko[key] ?? key, params);
  }

  variable(name, fallback) {
    return VARIABLES[name]?.[this.lang] ?? fallback ?? name;
  }

  defectType(code, fallback) {
    return DEFECT_TYPES[code]?.[this.lang] ?? fallback ?? code;
  }

  level(level) {
    return this.t(`level.${level}`);
  }

  /** 서버가 보낸 한국어 문구를 현재 언어로. 한국어 화면에서는 그대로 둔다. */
  text(korean) {
    if (this.lang === "ko" || korean == null) return korean;
    const exact = PHRASES[korean];
    if (exact) return exact;
    let out = String(korean);
    for (const [ko, en] of LABELS) out = out.replaceAll(ko, en);
    for (const [pattern, replacement] of RULES) out = out.replace(pattern, replacement);
    return out;
  }

  scenarioLabel(scenario) {
    return this.text(scenario.label);
  }
}

